    const mSoot = createMeas(tr.id, tr.investigation_id, 'soot_volume_fraction', 'outcome', 0.18, 'ppm', 0.0, 0.8, 'Soot Shell Imaging Diagnostics', 'Digital Shadowgraph Pyrometry', tr.source_ids[0], 6.0);
    measurements.push(mDiam, mBurnTime, mSoot);
    measIds.push(mDiam.id, mBurnTime.id, mSoot.id);
