// Helper to construct normalized measurements
let measurementCounter = 1;
function createMeas(
  testRunId: string,
  investigationId: string,
  paramCode: any,
  role: 'condition' | 'outcome',
  rawValue: number | null,
  rawUnit: string,
  minVal: number | null,
  maxVal: number | null,
  sensor: string | null,
  method: string | null,
  sourceId: string,
  time_s: number | null = null
): Measurement {
  const id = `MEAS-${String(measurementCounter++).padStart(4, '0')}`;
  const norm = normalizeParameterValue(paramCode, rawValue, rawUnit);

  const labels: Record<string, string> = {
    oxygen_concentration: 'Oxygen Concentration',
    airflow_velocity: 'Airflow Velocity',
    pressure: 'Ambient Pressure',
    temperature: 'Ambient Temperature',
    fuel_diameter: 'Fuel Sample Diameter',
    fuel_thickness: 'Fuel Sample Thickness',
    flame_spread_rate: 'Flame Spread Rate',
    burning_duration: 'Burning Duration',
    heat_release_rate: 'Heat Release Rate',
    carbon_monoxide_concentration: 'CO Concentration',
    carbon_dioxide_concentration: 'CO2 Concentration',
    particle_diameter: 'Smoke Particle Diameter',
    particle_number_concentration: 'Particle Number Concentration',
    particle_mass_concentration: 'Particle Mass Concentration',
    soot_volume_fraction: 'Soot Volume Fraction',
    smoke_aging_time: 'Smoke Aging Time',
    detector_response: 'Detector Output Response',
  };

  const categories: Record<string, any> = {
    oxygen_concentration: 'atmospheric_condition',
    airflow_velocity: 'flow_condition',
    pressure: 'atmospheric_condition',
    temperature: 'atmospheric_condition',
    fuel_diameter: 'fuel_geometry',
    fuel_thickness: 'fuel_geometry',
    flame_spread_rate: 'flame_dynamics',
    burning_duration: 'flame_dynamics',
    heat_release_rate: 'thermal_output',
    carbon_monoxide_concentration: 'gas_emissions',
    carbon_dioxide_concentration: 'gas_emissions',
    particle_diameter: 'smoke_aerosol',
    particle_number_concentration: 'smoke_aerosol',
    particle_mass_concentration: 'smoke_aerosol',
    soot_volume_fraction: 'soot_properties',
    smoke_aging_time: 'smoke_aerosol',
    detector_response: 'detection_response',
  };

  const displayUnits: Record<string, string> = {
    oxygen_concentration: '% vol',
    airflow_velocity: 'cm/s',
    pressure: 'kPa',
    temperature: 'K',
    fuel_diameter: 'mm',
    fuel_thickness: 'mm',
    flame_spread_rate: 'mm/s',
    burning_duration: 's',
    heat_release_rate: 'W',
    carbon_monoxide_concentration: 'ppm',
    carbon_dioxide_concentration: 'ppm',
    particle_diameter: 'nm',
    particle_number_concentration: '1/cm³',
    particle_mass_concentration: 'mg/m³',
    soot_volume_fraction: 'ppm',
    smoke_aging_time: 's',
    detector_response: 'V',
  };

  return {
    id,
    test_run_id: testRunId,
    investigation_id: investigationId,
    parameter_code: paramCode,
    parameter_label: labels[paramCode] || paramCode,
    parameter_category: categories[paramCode] || 'atmospheric_condition',
    measurement_role: role,
    raw_value: rawValue,
    raw_unit: rawUnit,
    normalized_value: norm.normalizedValue,
    normalized_unit: norm.normalizedUnit,
    display_unit: displayUnits[paramCode] || rawUnit,
    minimum_value: minVal,
    maximum_value: maxVal,
    time_s,
    sensor,
    measurement_method: method,
    uncertainty: rawValue !== null ? '±5% illustrative synthetic variance' : null,
    data_status: 'synthetic_demo',
    source_id: sourceId,
    source_page: null,
    is_mock: true,
  };
}

