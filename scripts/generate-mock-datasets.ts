  const measIds: string[] = [];

  // Conditions
  const mO2 = createMeas(tr.id, tr.investigation_id, 'oxygen_concentration', 'condition', tr.experimental_conditions.oxygen_pct_vol, '% vol', null, null, 'Chamber Zirconia O2 Sensor', 'Paramagnetic/Electrochemical Gas Analyzer', tr.source_ids[0]);
