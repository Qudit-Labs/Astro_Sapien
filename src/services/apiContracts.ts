/**
 * FIRELINE – FastAPI Analytics Endpoint Contracts
 *
 * TypeScript interfaces documenting the request/response shapes for
 * future POST-based module-analysis and AI endpoints served by the
 * FastAPI backend.  These are DOCUMENTATION ONLY — none of these
 * endpoints are currently implemented.  Set `VITE_DATA_MODE=api` and
 * supply `VITE_API_BASE_URL` to route data reads through
 * `ApiResearchDataProvider`.  POST endpoints listed here are planned
 * for a future backend sprint.
 *
 * Base path: /api/v1
 */

// ---------------------------------------------------------------------------
// 1. POST /api/v1/fireline/analyze
// ---------------------------------------------------------------------------

export interface FirelineAnalysisRequest {
  /** IDs of test runs to include in the analysis (1–50). */
  test_run_ids: string[];
  /** Optional list of parameter codes to restrict chart output. */
  parameter_codes?: string[];
  /** Gravity regime filter applied before analysis. */
  gravity_regime?: 'microgravity' | 'lunar' | 'martian' | 'normal_gravity' | 'all';
}

export interface FirelineParameterSummary {
  parameter_code: string;
  parameter_label: string;
  unit: string;
  min_value: number | null;
  max_value: number | null;
  mean_value: number | null;
  stddev: number | null;
  sample_count: number;
}

export interface FirelineAnalysisResult {
  request_id: string;
  created_at: string;
  run_count: number;
  summaries: FirelineParameterSummary[];
  /** Suggested findings derived from real NASA PSI/NTRS data. */
  generated_findings: string[];
  data_status: 'live' | 'cached' | 'synthetic_demo';
}

// ---------------------------------------------------------------------------
// 2. POST /api/v1/testmatch/compare
// ---------------------------------------------------------------------------

export interface TestMatchCompareRequest {
  /** ID of the first test run (run A). */
  test_run_a_id: string;
  /** ID of the second test run (run B). */
  test_run_b_id: string;
  /** Optional: restrict comparison to specific dimension codes. */
  dimension_codes?: string[];
}

export interface TestMatchDimensionResult {
  dimension_code: string;
  dimension_label: string;
  value_a: number | null;
  value_b: number | null;
  unit: string;
  status: 'similar' | 'different' | 'not_available' | 'not_comparable';
  deviation_pct: number | null;
  note?: string;
}

export interface TestMatchCompareResult {
  request_id: string;
  created_at: string;
  test_run_a_id: string;
  test_run_b_id: string;
  overall_score: number;         // 0–1 prototype comparability score
  comparable_dimensions: number;
  total_dimensions: number;
  dimensions: TestMatchDimensionResult[];
  similarities: string[];
  differences: string[];
  limitations: string[];
  data_status: 'live' | 'cached' | 'synthetic_demo';
}

// ---------------------------------------------------------------------------
// 3. POST /api/v1/smokewise/analyze
// ---------------------------------------------------------------------------

export interface SmokewiseAnalysisRequest {
  test_run_ids: string[];
  fuel_name?: string;
  gravity_regime?: string;
  /** Minimum particle diameter (nm) filter. */
  min_diameter_nm?: number;
  /** Maximum particle diameter (nm) filter. */
  max_diameter_nm?: number;
}

export interface SmokewiseAerosolSummary {
  fuel_name: string;
  run_count: number;
  mean_diameter_nm: number | null;
  mean_soot_volume_fraction: number | null;
  detector_sensitivity_note: string;
}

export interface SmokewiseAnalysisResult {
  request_id: string;
  created_at: string;
  aerosol_summaries: SmokewiseAerosolSummary[];
  /** ⚠ Particle diameter (nm) ≠ detector sensitivity. See sensor calibration docs. */
  scientific_caveats: string[];
  data_status: 'live' | 'cached' | 'synthetic_demo';
}

// ---------------------------------------------------------------------------
// 4. POST /api/v1/assistant/query
// ---------------------------------------------------------------------------

export interface AssistantQueryRequest {
  /** Natural-language research question. Max 1 000 characters. */
  question: string;
  /** Investigation IDs to restrict evidence retrieval. Empty = search all. */
  investigation_ids?: string[];
  /** Maximum number of evidence chunks to include in context. Default 5. */
  max_evidence_chunks?: number;
}

export interface AssistantCitation {
  source_id: string;
  source_title: string;
  evidence_chunk_id?: string;
  excerpt: string;
}

export interface AssistantQueryResult {
  request_id: string;
  question: string;
  answer: string;
  citations: AssistantCitation[];
  /** Whether the response was generated by an LLM (true) or keyword match (false). */
  llm_generated: boolean;
  /** Model name and version if llm_generated = true. */
  model_id?: string;
  is_mock_generated: boolean;
  synthetic_disclaimer: string;
}

// ---------------------------------------------------------------------------
// 5. POST /api/v1/reports/generate
// ---------------------------------------------------------------------------

export type ReportSectionKey =
  | 'executive_summary'
  | 'experiment_overview'
  | 'flame_behavior'
  | 'smoke_aerosol'
  | 'test_comparison'
  | 'gaps_limitations'
  | 'findings_conclusions'
  | 'methodology'
  | 'references';

export interface ReportGenerateRequest {
  /** Investigation IDs to include in the report. */
  investigation_ids: string[];
  /** Sections to include. Empty = all sections. */
  sections?: ReportSectionKey[];
  /** Report output format. */
  format: 'json' | 'markdown' | 'pdf';
  /** Optional title override. */
  title?: string;
}

export interface ReportGenerateResult {
  request_id: string;
  created_at: string;
  title: string;
  format: 'json' | 'markdown' | 'pdf';
  /** Markdown or JSON string; for PDF, a signed download URL. */
  content: string;
  /** Estimated confidence score 0–1 based on data completeness. */
  confidence_score: number;
  data_status: 'live' | 'cached' | 'synthetic_demo';
  synthetic_disclaimer: string;
}

// ---------------------------------------------------------------------------
// 6. GET /api/v1/evidence/search  (query-param based)
// ---------------------------------------------------------------------------

export interface EvidenceSearchFilters {
  investigation_id?: string;
  source_id?: string;
  /** Maximum results to return. Default 10, max 50. */
  limit?: number;
}

export interface EvidenceSearchResult {
  query: string;
  results: Array<{
    chunk_id: string;
    investigation_id: string;
    source_id: string;
    relevance_score: number;   // 0–1
    excerpt: string;
  }>;
  total_found: number;
}

// ---------------------------------------------------------------------------
// 7. POST /api/v1/ingestion/trigger  (admin; requires API key header)
// ---------------------------------------------------------------------------

export interface IngestionTriggerRequest {
  /** Data sources to ingest. */
  sources: Array<'nasa_psi' | 'ntrs' | 'nfpa'>;
  /** Dry-run does not write to database; only validates fetched records. */
  dry_run?: boolean;
}

export interface IngestionTriggerResult {
  job_id: string;
  status: 'queued' | 'running' | 'complete' | 'failed';
  records_fetched: number;
  records_inserted: number;
  errors: string[];
}

// ---------------------------------------------------------------------------
